<?php

/**
 * Writes `updates.xml` from the package manifest.
 *
 *   php build/update-xml.php              keep the committed checksum while it still fits
 *   php build/update-xml.php --checksum   hash the archive built in build/
 *
 * Joomla's update server repeats what the manifest already says - element,
 * version, platform - next to the URL of the package for that version. Repeated
 * by hand it drifts, so it is generated, and UpdateServerTest fails when the
 * committed file and the manifest disagree.
 *
 * The checksum can only be written by the release workflow: the archive is
 * built there, and one built anywhere else differs in timestamps.
 */

declare(strict_types=1);

$root = \dirname(__DIR__);
$xml  = simplexml_load_file($root . '/src/pkg_mdimport.xml');

if ($xml === false) {
    fwrite(STDERR, "Cannot read src/pkg_mdimport.xml.\n");
    exit(1);
}

$version = trim((string) $xml->version);
$element = 'pkg_' . trim((string) $xml->packagename);

$script      = (string) file_get_contents($root . '/src/script.php');
$joomlaFloor = preg_match("/minimumJoomlaVersion\s*=\s*'([^']+)'/", $script, $m) ? $m[1] : '';
$phpFloor    = preg_match("/minimumPHPVersion\s*=\s*'([^']+)'/", $script, $m) ? $m[1] : '';

if ($version === '' || $joomlaFloor === '' || $phpFloor === '') {
    fwrite(STDERR, "The package needs a version, and script.php a minimum Joomla and PHP.\n");
    exit(1);
}

$download = \sprintf('https://github.com/HermanPeeren/md-import/releases/download/v%1$s/%2$s-%1$s.zip', $version, $element);

// Every major from the minimum up to the one this is developed against: the
// platform is a regular expression, and "5\..*" alone would hide the update
// from a Joomla 6 site.
$platform = '(' . implode('|', range((int) explode('.', $joomlaFloor)[0], 6)) . ')\..*';

$sha512 = null;

if (\in_array('--checksum', $argv, true)) {
    $archive = $root . '/build/' . basename($download);

    if (!is_file($archive)) {
        fwrite(STDERR, "--checksum hashes the built archive, and there is none at {$archive}.\n");
        exit(1);
    }

    $sha512 = hash_file('sha512', $archive);
} elseif (is_file($root . '/updates.xml')) {
    $committed = simplexml_load_file($root . '/updates.xml');

    if ($committed !== false && trim((string) $committed->update->downloads->downloadurl) === $download) {
        $sha512 = trim((string) $committed->update->sha512) ?: null;
    }
}

$checksum = $sha512 === null ? '' : "\t\t<sha512>{$sha512}</sha512>\n";

$updates = <<<XML
<?xml version="1.0" encoding="utf-8"?>
<!--
	Generated by build/update-xml.php from src/pkg_mdimport.xml. Do not edit by
	hand: run the script and commit the result.
-->
<updates>
	<update>
		<name>MD Import</name>
		<description>Imports the Joomla help pages from Jdocmanual as articles, images and menu items.</description>
		<element>{$element}</element>
		<type>package</type>
		<version>{$version}</version>
		<downloads>
			<downloadurl type="full" format="zip">{$download}</downloadurl>
		</downloads>
{$checksum}		<maintainer>Herman Peeren</maintainer>
		<maintainerurl>https://yepr.nl</maintainerurl>
		<targetplatform name="joomla" version="{$platform}"/>
		<php_minimum>{$phpFloor}</php_minimum>
	</update>
</updates>

XML;

file_put_contents($root . '/updates.xml', $updates);

echo "updates.xml written for {$element} {$version}" . ($sha512 === null ? ', without a checksum' : ', with its checksum') . "\n";
